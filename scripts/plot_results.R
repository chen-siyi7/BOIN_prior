script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
source(file.path(dirname(normalizePath(script)), "common.R"))
root <- script_root()
args <- arguments(c("input", "output"))
if (is.null(args$input) || is.null(args$output))
  stop("Supply --input with reproduced results and --output with a new figure directory.")
source(file.path(root, "R/project.R"))
output <- boin_output(args$output, root)
source(file.path(root, "R/plots.R"))
files <- plot_results(args$input, output)
cat("R graphics created", length(files), "PDF and PNG files in", output, "\n")
