script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
source(file.path(dirname(normalizePath(script)), "common.R"))
root <- script_root()
source(file.path(root, "R/project.R"))
args <- arguments(c("counts", "dlts", "table"))
if (is.null(args$counts) || is.null(args$dlts))
  stop("Supply --counts and --dlts as comma-separated integer vectors.")
project <- boin_project(root)
counts <- suppressWarnings(as.numeric(strsplit(args$counts, ",", fixed = TRUE)[[1]]))
dlts <- suppressWarnings(as.numeric(strsplit(args$dlts, ",", fixed = TRUE)[[1]]))
table <- if (is.null(args$table)) "central_sparse90" else args$table
result <- project$select_dose(counts, dlts, table)
cat("BOIN recommendation:", result$BOIN, "\n")
cat("Final recommendation:", result$recommendation, "\n")
